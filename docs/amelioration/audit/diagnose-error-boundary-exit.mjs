import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const prefix = 'docs/amelioration/audit/error-boundary-exit-diagnostic';
const sha = file => createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
const files = ['src/components/common/ErrorBoundary.test.tsx', 'src/components/common/ErrorBoundary.tsx', 'vitest.config.ts', 'src/test/setup.ts', 'package-lock.json', 'docs/amelioration/audit/run-end-errors-reporter.mjs'];
const hashes = () => Object.fromEntries(files.map(file => [file, sha(file)]));
const before = hashes();
for (const suffix of ['.json', '.stdout.txt', '.stderr.txt', '.run-end.json', '.evidence.json']) if (fs.existsSync(path.join(root, prefix + suffix))) throw new Error('Ne pas écraser la preuve précédente');
const args = ['node_modules/vitest/vitest.mjs', 'run', '--maxWorkers=1', '--reporter=default', '--reporter=json', '--reporter=./docs/amelioration/audit/run-end-errors-reporter.mjs', `--outputFile.json=${prefix}.json`, 'src/components/common/ErrorBoundary.test.tsx'];
const startedAt = new Date().toISOString();
const result = spawnSync(process.execPath, args, { cwd: root, encoding: 'utf8', windowsHide: true, timeout: 180000, env: { ...process.env, NO_COLOR: '1', AUDIT_RUN_END_FILE: path.join(root, prefix + '.run-end.json') } });
fs.writeFileSync(path.join(root, prefix + '.stdout.txt'), result.stdout || '');
fs.writeFileSync(path.join(root, prefix + '.stderr.txt'), result.stderr || '');
const read = suffix => fs.existsSync(path.join(root, prefix + suffix)) ? JSON.parse(fs.readFileSync(path.join(root, prefix + suffix), 'utf8')) : null;
const json = read('.json');
const end = read('.run-end.json');
const after = hashes();
const evidence = { id: 'AUD-ERROR-BOUNDARY-EXIT-20260907', startedAt, finishedAt: new Date().toISOString(), command: ['node', ...args].join(' '), exitCode: result.status, processError: result.error?.message || null, passed: json?.numPassedTests, failed: json?.numFailedTests, total: json?.numTotalTests, reason: end?.reason, unhandledErrors: end?.unhandledErrors, stableInputs: JSON.stringify(before) === JSON.stringify(after), before, after, replacesGlobalRun: false };
fs.writeFileSync(path.join(root, prefix + '.evidence.json'), JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify(evidence));
if (result.status !== 0) process.exitCode = 1;
